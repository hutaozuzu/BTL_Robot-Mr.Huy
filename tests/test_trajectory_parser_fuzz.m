function test_trajectory_parser_fuzz()
% TEST_TRAJECTORY_PARSER_FUZZ Adversarial fuzz testing suite for trajectory_parser.m.
%
% Generates >= 35 malformed, corrupted, boundary, and edge-case trajectory files
% in both CSV and JSON formats to stress-test trajectory_parser.m:
%   - Corrupted headers, missing columns, delimiter issues
%   - NaN, Inf, non-numeric strings, array/object types in coordinates
%   - Huge coordinates (>10^6 mm), out-of-envelope radii, Z-ceiling/floor violations
%   - Truncated JSON syntax, malformed root types, missing waypoints field
%   - Zero durations, negative durations, NaN/Inf durations
%   - Invalid action verbs, empty actions, non-string actions
%   - Kinematically unreachable poses within the radial reach envelope
%   - Non-existent files and unsupported extensions
%
% Strictly native MATLAB (No Peter Corke Robotics Toolbox).

    tests_dir = fileparts(mfilename('fullpath'));
    base_dir = fullfile(tests_dir, '..');
    gui_dir = fullfile(base_dir, 'gui');
    kin_dir = fullfile(base_dir, 'kinematics');
    
    addpath(gui_dir);
    addpath(kin_dir);
    
    % Dedicated temporary directory for fuzz artifacts
    fuzz_tmp_dir = fullfile(base_dir, 'data', 'fuzz_artifacts');
    if ~exist(fuzz_tmp_dir, 'dir')
        mkdir(fuzz_tmp_dir);
    end

    fprintf('\n================================================================================\n');
    fprintf('  ADVERSARIAL FUZZ TEST SUITE: trajectory_parser.m (Empirical Challenger M4-2)  \n');
    fprintf('================================================================================\n\n');

    test_cases = define_fuzz_cases(fuzz_tmp_dir);
    n_cases = numel(test_cases);

    results = struct('id', {}, 'category', {}, 'name', {}, 'is_valid', {}, ...
                     'error_msg', {}, 'crashed', {}, 'passed', {}, 'notes', {});

    n_pass = 0;
    n_fail = 0;
    n_crashes = 0;

    for i = 1:n_cases
        tc = test_cases(i);
        t_start = tic;
        crashed = false;
        crash_msg = '';
        actual_is_valid = true;
        actual_err = '';
        actual_wp = [];

        % Generate file if generator function exists
        filepath = tc.filepath;
        if ~isempty(tc.generator)
            try
                tc.generator(filepath);
            catch gen_err
                fprintf('  [ERROR] Test setup failed for %s: %s\n', tc.id, gen_err.message);
                continue;
            end
        end

        % Invoke trajectory_parser inside strict try/catch to detect any uncaught exception
        try
            [actual_wp, actual_is_valid, actual_err] = trajectory_parser(filepath);
        catch ME
            crashed = true;
            crash_msg = ME.message;
            actual_is_valid = false;
            actual_err = sprintf('UNCAUGHT EXCEPTION: %s', ME.message);
        end
        t_elapsed = toc(t_start) * 1000;

        % Cleanup file if created
        if exist(filepath, 'file') && ~tc.keep_file
            delete(filepath);
        end

        % Evaluation criteria:
        % 1. Must NEVER crash with uncaught MATLAB exception.
        % 2. If expected_valid == false:
        %    - actual_is_valid must be false
        %    - actual_err must be non-empty character vector
        %    - actual_wp must be empty
        % 3. If expected_valid == true:
        %    - actual_is_valid must be true
        %    - actual_err must be empty
        %    - actual_wp must have valid entries
        test_passed = false;
        notes = '';

        if crashed
            n_crashes = n_crashes + 1;
            test_passed = false;
            notes = sprintf('CRASHED: %s', crash_msg);
        elseif tc.expected_valid == false
            if actual_is_valid == false && ~isempty(actual_err) && isempty(actual_wp)
                test_passed = true;
                notes = sprintf('Correctly rejected: "%s"', actual_err);
            elseif actual_is_valid == true
                test_passed = false;
                notes = sprintf('FAULT: Expected rejection, but parser returned is_valid=true!');
            elseif isempty(actual_err)
                test_passed = false;
                notes = 'FAULT: is_valid=false but error_msg was empty';
            elseif ~isempty(actual_wp)
                test_passed = false;
                notes = 'FAULT: is_valid=false but non-empty waypoints returned';
            end
        else % expected_valid == true
            if actual_is_valid == true && isempty(actual_err) && ~isempty(actual_wp)
                test_passed = true;
                notes = sprintf('Correctly accepted %d waypoints', numel(actual_wp));
            else
                test_passed = false;
                notes = sprintf('FAULT: Expected valid, but got err: %s', actual_err);
            end
        end

        if test_passed
            n_pass = n_pass + 1;
            status_str = 'PASS';
        else
            n_fail = n_fail + 1;
            status_str = 'FAIL';
        end

        fprintf('  [%s] %s [%-12s] %-48s (%.1f ms)\n', ...
            status_str, tc.id, tc.category, tc.name, t_elapsed);
        if ~test_passed
            fprintf('         -> Details: %s\n', notes);
        end

        results(i).id = tc.id;
        results(i).category = tc.category;
        results(i).name = tc.name;
        results(i).is_valid = actual_is_valid;
        results(i).error_msg = actual_err;
        results(i).crashed = crashed;
        results(i).passed = test_passed;
        results(i).notes = notes;
    end

    % Clean up temporary directory
    if exist(fuzz_tmp_dir, 'dir')
        try rmdir(fuzz_tmp_dir, 's'); catch; end
    end

    fprintf('\n--------------------------------------------------------------------------------\n');
    fprintf('  FUZZ TEST SUMMARY: Total = %d | PASS = %d | FAIL = %d | CRASHES = %d\n', ...
        n_cases, n_pass, n_fail, n_crashes);
    fprintf('--------------------------------------------------------------------------------\n\n');

    % Save results report
    save(fullfile(tests_dir, 'fuzz_results.mat'), 'results');
end

